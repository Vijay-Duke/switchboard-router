import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const registryDir = path.join(root, "open-sse", "providers", "registry");
const target = path.join(registryDir, "index.js");

export function listRegistryFiles(dir = registryDir) {
  return fs.readdirSync(dir)
    .filter((name) => name.endsWith(".js") && name !== "index.js" && name !== "REGISTRY_TEMPLATE.js")
    .sort();
}

export function buildRegistryOutput(files) {
  const imports = files.map((name, index) => `import p${index} from "./${name}";`).join("\n");
  const entries = files.map((_, index) => `  p${index}`).join(",\n");
  return `// Auto-generated by scripts/generate-provider-registry.mjs. Do not edit.\n${imports}\n\nconst providerRegistry = [\n${entries}\n];\n\nexport default providerRegistry;\n`;
}

// Windows CRLF checkouts read the committed file back with \r\n; compare
// normalized text so --check is not spuriously stale there.
export function registryUpToDate(current, output) {
  return current.replace(/\r\n/g, "\n") === output;
}

export function main(argv = process.argv.slice(2), { dir = registryDir, file = target } = {}) {
  const files = listRegistryFiles(dir);
  const output = buildRegistryOutput(files);
  if (argv.includes("--check")) {
    const current = fs.readFileSync(file, "utf8");
    if (!registryUpToDate(current, output)) {
      console.error("Provider registry is stale. Run npm run generate:providers.");
      process.exit(1);
    }
  } else {
    fs.writeFileSync(file, output);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
